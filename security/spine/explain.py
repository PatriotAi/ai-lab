#!/usr/bin/env python3
"""explain.py — перетворює технічний вердикт на пояснення звичайними словами.

Єдина відповідальність: сказати людині, яка не розуміється в коді, ЩО саме
зупинено, ЧОМУ, ЯК можна інакше — і ЩО це дає натомість.

ЧОМУ ЦЕ ОКРЕМИЙ ФАЙЛ І ЧОМУ ВІН ТАКИЙ ДОКЛАДНИЙ.
Директива власника (2026-07-27): «блокувати і питати… під час запиту
максимально деталізовано звичайними словами для людини, яка не розуміється
в інформатиці, пояснювати чому саме так або відповідно інші можливості, і що
саме це надає за можливості приймати автоматизовані рішення, якщо вони
перевірено являються безпечними».

Тобто зупинка — це не відмова, а РОЗМОВА. Повідомлення, що просто каже
«заборонено», перетворює гейт на перешкоду, яку захочеться обійти — а обхід
гейтів задокументований як головна причина їхньої марності.

ЧОМУ ТУТ НЕМАЄ ЖОДНОГО ВИКЛИКУ МОДЕЛІ. Пояснення складається з тексту, що вже
лежить у `security/policy.toml`. Це нуль токенів і нуль затримки: дорогий шар
(розбір змісту моделлю) вмикається лише там, де дешевий дав підозру.
"""
from __future__ import annotations

import sys

from classify import Verdict  # noqa: E402  (шлях додає викликач)

# Що кожен рівень означає простими словами — і що він дозволяє робити САМОСТІЙНО.
LEVEL_MEANING = {
    "R0": (
        "читання",
        "Я лише дивлюсь і нічого не змінюю.",
        "Такі дії йдуть без жодних перевірок і без твоєї участі — саме тому "
        "робота лишається швидкою.",
    ),
    "R1": (
        "звичайна правка файлу в проєкті",
        "Я змінюю файл усередині цього проєкту. Кожна така зміна видима в історії "
        "й відкочується однією командою.",
        "Такі дії я роблю сам. Якщо щось піде не так — попередній стан на місці.",
    ),
    "R2": (
        "команда з можливими наслідками",
        "Я запускаю команду, яка щось робить, а не лише дивиться.",
        "Такі дії я роблю сам, але вони записуються — завжди видно, що саме сталося.",
    ),
    "R3": (
        "текст із зовнішнього джерела",
        "У мою пам'ять або контекст потрапляє текст, якого не писав ти. Всередині "
        "такого тексту можуть бути сховані вказівки, розраховані на те, що я їх "
        "виконаю, вважаючи твоїми.",
        "Такий текст я приймаю тільки як ДАНІ — щось, про що можна розповісти, — "
        "а не як команди. Перевірка на приховані вказівки відбувається автоматично.",
    ),
    "R4": (
        "незворотна дія або дія назовні",
        "Це те, що не відкотиш звичайним способом, або те, що побачать інші.",
        "Саме тут я зупиняюсь і питаю тебе.",
    ),
}


def render(v: Verdict, tool_name: str, decision: str) -> str:
    """Складає повідомлення. `decision` — deny / ask / warn / allow."""
    label, meaning, capability = LEVEL_MEANING.get(
        v.level, ("невідомий клас дії", "", "")
    )
    lines: list[str] = []

    if decision == "deny":
        lines.append("🛑 ЗУПИНЕНО — потрібна твоя згода")
    elif decision == "ask":
        lines.append("❓ ПОТРІБНЕ ПІДТВЕРДЖЕННЯ")
    else:
        lines.append("⚠️ ПОПЕРЕДЖЕННЯ")

    lines.append("")
    lines.append(f"ЩО Я ХОТІВ ЗРОБИТИ: {_action_phrase(tool_name, v)}")
    lines.append(f"ЯК ЦЕ КЛАСИФІКОВАНО: {v.level} — {label}")

    # Симлінк — окремим блоком і першим, бо він змінює саму суть згоди.
    for note in v.notes:
        lines.append("")
        lines.append(f"❗ {note}")
        lines.append(
            "   Тобто назва файлу показує одне, а зачепить інше. Якщо ти цього "
            "не замовляв — це ознака підміни, і погоджуватись не варто."
        )

    if v.why:
        lines.append("")
        lines.append("ЧОМУ ЦЕ ВАЖЛИВО:")
        lines.append(f"   {v.why}")
    elif meaning:
        lines.append("")
        lines.append("ЩО ЦЕ ОЗНАЧАЄ:")
        lines.append(f"   {meaning}")

    if v.alternatives:
        lines.append("")
        lines.append("ЯК МОЖНА ІНАКШЕ:")
        lines.append(f"   {v.alternatives}")

    lines.append("")
    lines.append("ЩО ЦЕ ДАЄ ТОБІ:")
    lines.append(
        "   Оскільки цей клас дій зупиняється й питає, всі інші класи я можу "
        "виконувати САМОСТІЙНО, не смикаючи тебе щоразу."
    )
    lines.append(
        "   Читання й звичайні правки в проєкті йдуть без питань; команди — "
        "записуються; зовнішній текст — перевіряється сам."
    )
    lines.append(
        "   Тобто питання виникає рідко саме тому, що межа проведена чітко. "
        "Це і є те, заради чого гейт існує: тобі не треба вникати в код, щоб "
        "довіряти решті."
    )

    if decision == "deny":
        lines.append("")
        lines.append(
            "ЩО РОБИТИ: якщо ця дія справді потрібна — скажи про це прямо, "
            "і я виконаю її з твоєю згодою. Якщо ти не розумієш, навіщо вона — "
            "це достатня причина сказати «ні»: без неї нічого не зламається."
        )

    return "\n".join(lines)


def _action_phrase(tool_name: str, v: Verdict) -> str:
    target = v.resolved_target or v.target or "(без цілі)"
    if tool_name == "Bash":
        return f"виконати команду: {target}"
    if tool_name in ("Write", "Edit", "NotebookEdit"):
        return f"змінити файл: {target}"
    if tool_name in ("WebFetch", "WebSearch"):
        return f"взяти текст із зовнішнього джерела: {target}"
    return f"{tool_name}: {target}"


def main(argv: list[str]) -> int:
    """Демонстрація: показати, як виглядатиме повідомлення для дії."""
    if len(argv) < 3:
        print("вжиток: explain.py <Tool> <команда-або-шлях>", file=sys.stderr)
        return 2
    from classify import classify  # локальний імпорт — щоб файл лишався модулем

    tool, payload = argv[1], argv[2]
    tool_input = {"command": payload} if tool == "Bash" else {"file_path": payload}
    v = classify(tool, tool_input)
    decision = "deny" if v.level == "R4" else "allow"
    print(render(v, tool, decision))
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
    raise SystemExit(main(sys.argv))
